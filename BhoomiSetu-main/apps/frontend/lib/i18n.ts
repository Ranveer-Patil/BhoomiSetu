export const useLocale = create<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
}>()(
  persist((set) => ({ locale: "en", setLocale: (locale) => set({ locale }) }), {
    name: "bhoomisetu-locale",
    skipHydration: true,
  }),
);
export function translate(key: string, locale: Locale) {
  return messages[key]?.[localeIndex[locale]] ?? key.replaceAll("_", " ");
}
export function useT() {
  const locale = useLocale((state) => state.locale);
  return (key: string) => translate(key, locale);
}
